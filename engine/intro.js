// wang-motion v10 — unified timeline + per-card intro layer.
// Pure module (only needs THREE passed in). Shared by the CLI page (engine/index.html), the web app bundle and the HTML player.
//
// Timeline (wall-clock seconds T):  [ intro | hold | ramp-in loop … ]
//   template clock  tau = T * speed            (speed scales the WHOLE timeline, intro included)
//   tau < I         -> pose frozen at phase0, intro progress P = tau / I
//   tau < I + H     -> pose frozen, P = 1 (formed, untouched)
//   after           -> t = phase0*D + ramp(tau - I - H)   (ramp eases 0 -> full speed over R s, costs R/2 s)
// With intro mode 'none' the map is t = tau (plain v9 behaviour, no ramp, no freeze).

export const INTRO_DEFAULTS = { mode: 'none', style: 'rise', order: 'index', dur: 2.5, hold: 0.3, seed: 1, ramp: 0.4, phase: null };
export const INTRO_STYLES = ['rise', 'fly', 'pop', 'flip'];
export const INTRO_ORDERS = ['index', 'center', 'ltr', 'random'];
export const SPEED_MIN = 0.1, SPEED_MAX = 8;
import INTRO_COMPAT_T from './intro-compat.js';

// Templates whose phase 0 is a poor "formed" pose (mid-cut / flash / empty stage) start the intro elsewhere.
// Filled from the v10 regression (intro sheets); everything else starts at phase 0.
export const START_PHASE = {
  'grid-reveal': 0.5, 'cascade-drop': 0.7, 'bloom-belt': 0.2, 'fan-shuffle': 0.4, 'sweep-ring': 0.7, 'triple-scene': 0.45, 'mosaic-reveal': 0.125,
};

// Per-template stagger suitability (generated by tools/intro-compat.mjs; also read by `wm info` and the web UI).
// value: { v: visible cards at the start pose, ok: stagger usable }  — templates missing here are probed at runtime.
export { default as INTRO_COMPAT } from './intro-compat.js';

export function normIntro(spec) {
  const s = spec && spec.intro;
  if (!s || s === 'none') return { ...INTRO_DEFAULTS };
  const o = typeof s === 'string' ? { mode: s } : s;
  const r = { ...INTRO_DEFAULTS, ...o };
  if (!['none', 'stagger', 'whole'].includes(r.mode)) r.mode = 'none';
  if (!INTRO_STYLES.includes(r.style)) r.style = 'rise';
  if (!INTRO_ORDERS.includes(r.order)) r.order = 'index';
  r.dur = Math.max(0.2, Number(r.dur) || INTRO_DEFAULTS.dur);
  r.hold = Math.max(0, Number(r.hold ?? INTRO_DEFAULTS.hold));
  r.ramp = Math.max(0, Number(r.ramp ?? INTRO_DEFAULTS.ramp));
  r.seed = Number(r.seed ?? 1) | 0;
  return r;
}
export function normSpeed(v) { const s = Number(v); return isFinite(s) && s > 0 ? Math.min(SPEED_MAX, Math.max(SPEED_MIN, s)) : 1; }

// D = loop duration of the template at 1x (spec.duration)
export function timelineInfo(spec, D, tplId) {
  const speed = normSpeed(spec && spec.speed);
  const intro = normIntro(spec);
  const on = intro.mode !== 'none';
  const phase0 = on ? (intro.phase != null ? ((Number(intro.phase) % 1) + 1) % 1 : (START_PHASE[tplId] ?? 0)) : 0;
  const I = on ? intro.dur : 0, H = on ? intro.hold : 0, R = on ? Math.min(intro.ramp, D * 0.5) : 0;
  const pre = I + H + R / 2; // template seconds before the loop is "on beat"
  return {
    speed, intro, on, phase0, D, I, H, R,
    introWall: (I + H) / speed,           // wall seconds of intro + hold
    preWall: pre / speed,                 // intro + hold + ramp debt
    loopWall: D / speed,                  // one loop in wall seconds
    total: (loops = 1) => pre / speed + Math.max(0, loops) * D / speed,
  };
}
// T (wall seconds) -> { t: template seconds for layout, P: intro progress (null = no intro modification) }
export function timeMap(T, info) {
  const tau = T * info.speed;
  if (!info.on) return { t: tau, P: null };
  const base = info.phase0 * info.D;
  if (tau < info.I) return { t: base, P: Math.max(0, tau / info.I) };
  if (tau < info.I + info.H) return { t: base, P: null };
  const x = tau - info.I - info.H, R = info.R;
  const w = R > 0 && x < R ? (x * x) / (2 * R) : x - R / 2;
  return { t: base + w, P: null };
}

// ---------------- intro layer ----------------
const clamp = (v, a = 0, b = 1) => Math.min(b, Math.max(a, v));
const outCubic = (x) => 1 - Math.pow(1 - x, 3);
const outQuint = (x) => 1 - Math.pow(1 - x, 5);
const outBack = (x) => { const c1 = 1.70158, c3 = c1 + 1; return 1 + c3 * Math.pow(x - 1, 3) + c1 * Math.pow(x - 1, 2); };
function mulberry32(a) { return () => { a |= 0; a = (a + 0x6d2b79f5) | 0; let t = Math.imul(a ^ (a >>> 15), 1 | a); t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t; return ((t ^ (t >>> 14)) >>> 0) / 4294967296; }; }

let _T = null; const V = {};
function vecs(THREE) {
  if (_T === THREE) return V; _T = THREE;
  V.p = new THREE.Vector3(); V.n = new THREE.Vector3(); V.d = new THREE.Vector3(); V.up = new THREE.Vector3(); V.q = new THREE.Quaternion(); V.q2 = new THREE.Quaternion();
  V.e = new THREE.Euler(); V.ax = new THREE.Vector3(0, 1, 0); V.cam = new THREE.Vector3();
  return V;
}

// classify the cards of the frozen start pose: which are "visible" (front-facing, inside the frame, not tiny)
export function introAnalyze(cards, camera, THREE) {
  const v = vecs(THREE); camera.updateMatrixWorld(); v.cam.copy(camera.position);
  const out = [];
  for (let i = 0; i < cards.length; i++) {
    const c = cards[i];
    if (!c || c.hidden || (c.opacity ?? 1) <= 0.001) { out.push(null); continue; }
    const extra = !!c.light || c.introExtra === true;
    const mirror = !!c.mirrorY;
    v.p.set(c.x || 0, c.y || 0, c.z || 0);
    v.d.copy(v.p).project(camera);
    const inFrame = v.d.z > -1 && v.d.z < 1 && Math.abs(v.d.x) <= 1.04 && Math.abs(v.d.y) <= 1.04;
    v.e.set(c.rx || 0, c.ry || 0, c.rz || 0, c.order || 'YXZ'); v.n.set(0, 0, 1).applyEuler(v.e);
    const toCam = v.up.copy(v.cam).sub(v.p);
    const dist = toCam.length();
    const front = c.device ? true : v.n.dot(toCam) > 0.02 * dist;
    // projected size (fraction of frame height)
    const w = c.w ?? 0.3; const s = c.s ?? 1; const fovK = 1 / Math.tan((camera.fov * Math.PI) / 360);
    const size = (w * s * fovK) / Math.max(1e-4, dist);
    const vis = !extra && !mirror && inFrame && front && size > 0.012;
    out.push({ i, extra, mirror, vis, sx: v.d.x * camera.aspect, sy: v.d.y, dist, media: c.media });
  }
  return out;
}
export function visibleCount(cards, camera, THREE) { let n = 0; for (const a of introAnalyze(cards, camera, THREE)) if (a && a.vis) n++; return n; }

// Build per-card start offsets (seconds inside the intro) for the frozen pose.
function schedule(an, intro) {
  const I = intro.dur;
  const vis = an.filter((a) => a && a.vis);
  let mode = intro.mode;
  if (mode === 'stagger' && vis.length < 3) mode = 'whole';
  const plan = new Map(); // i -> [start, len]
  if (mode === 'whole') {
    const len = I * 0.85;
    for (const a of an) if (a && !a.extra) plan.set(a.i, [0, len]);
    return { plan, mode, extra: [I * 0.55, I * 0.45] };
  }
  const d = Math.min(I * 0.9, clamp(I * 0.35, 0.25, 0.8));
  let ord = vis.slice();
  if (intro.order === 'center') ord.sort((a, b) => (a.sx * a.sx + a.sy * a.sy) - (b.sx * b.sx + b.sy * b.sy) || a.i - b.i);
  else if (intro.order === 'ltr') ord.sort((a, b) => (a.sx - b.sx) || (b.sy - a.sy) || a.i - b.i);
  else if (intro.order === 'random') { const r = mulberry32(intro.seed * 2654435761 + 1); for (let k = ord.length - 1; k > 0; k--) { const j = Math.floor(r() * (k + 1)); [ord[k], ord[j]] = [ord[j], ord[k]]; } }
  const n = ord.length; const gap = n > 1 ? (I - d) / (n - 1) : 0;
  ord.forEach((a, k) => plan.set(a.i, [k * gap, d]));
  const last = (n - 1) * gap;
  // mirror reflections follow the nearest visible card of the same media (else the closest on screen); hidden / off-frame cards come with the last one
  for (const a of an) {
    if (!a || a.extra || plan.has(a.i)) continue;
    if (a.mirror) {
      let best = null, bd = 1e9;
      for (const b of vis) { const dd = Math.abs(b.sx - a.sx) + (b.media === a.media ? 0 : 10); if (dd < bd) { bd = dd; best = b; } }
      plan.set(a.i, best ? plan.get(best.i) : [last, d]); continue;
    }
    plan.set(a.i, [last, d]);
  }
  return { plan, mode, extra: [I * 0.8, I * 0.2] };
}

// Apply the intro to the frozen pose. P = intro progress 0..1. Mutates copies; returns { cards, fxA }.
export function applyIntro(cards, P, intro, camera, THREE) {
  const v = vecs(THREE);
  const an = introAnalyze(cards, camera, THREE);
  const { plan, extra } = schedule(an, intro);
  const T = P * intro.dur;
  const fxA = outCubic(clamp((T - extra[0]) / Math.max(1e-4, extra[1])));
  const camDist = v.cam.length() || 1;
  camera.getWorldDirection(v.d); // forward
  const upW = v.up.set(0, 1, 0).applyQuaternion(camera.quaternion); const upX = upW.x, upY = upW.y, upZ = upW.z;
  const out = new Array(cards.length);
  for (let i = 0; i < cards.length; i++) {
    const c = cards[i]; const a = an[i];
    if (!c || !a) { out[i] = c; continue; }
    if (a.extra) { out[i] = { ...c, opacity: (c.opacity ?? 1) * fxA }; continue; }
    const pl = plan.get(i) || [0, intro.dur];
    const k = clamp((T - pl[0]) / Math.max(1e-4, pl[1]));
    if (k >= 1) { out[i] = c; continue; }
    if (k <= 0) { out[i] = { ...c, opacity: 0 }; continue; }
    const o = { ...c }; const op0 = c.opacity ?? 1;
    const st = a.mirror ? (intro.style === 'pop' ? 'pop' : 'fade') : intro.style;
    const kd = a.dist / camDist; // keeps offsets screen-proportional at any depth
    if (st === 'fade') { o.opacity = op0 * outCubic(k); }
    else if (st === 'rise') {
      const e = outQuint(k); const off = (1 - e) * 0.09 * kd;
      o.x = (c.x || 0) - upX * off; o.y = (c.y || 0) - upY * off; o.z = (c.z || 0) - upZ * off;
      o.opacity = op0 * clamp(k / 0.55);
    } else if (st === 'fly') {
      const e = outCubic(k); const f = (1 - e) * 2.2; // push away along the view ray (keeps the screen position)
      const px = c.x || 0, py = c.y || 0, pz = c.z || 0;
      o.x = px + (px - v.cam.x) * f; o.y = py + (py - v.cam.y) * f; o.z = pz + (pz - v.cam.z) * f;
      o.opacity = op0 * clamp(k / 0.4);
    } else if (st === 'pop') {
      const e = outBack(k); o.s = (c.s ?? 1) * Math.max(0.001, e);
      o.opacity = op0 * clamp(k / 0.3);
    } else if (st === 'flip') {
      const e = outCubic(k); const ang = (1 - e) * (Math.PI / 2) * 0.98;
      v.e.set(c.rx || 0, c.ry || 0, c.rz || 0, c.order || 'YXZ'); v.q.setFromEuler(v.e); v.q2.setFromAxisAngle(v.ax, ang); v.q.multiply(v.q2);
      v.e.setFromQuaternion(v.q, c.order || 'YXZ'); o.rx = v.e.x; o.ry = v.e.y; o.rz = v.e.z;
      o.opacity = op0 * clamp(k / 0.25);
    }
    if (c.shadow != null) o.shadow = c.shadow * k;
    out[i] = o;
  }
  return { cards: out, fxA };
}

// scale a normalised template post (normTplPost output) by a 0..1 factor (glitch / flash / bloom fade in with the extras)
export function scalePost(pp, a) {
  if (!pp || a >= 1) return pp;
  const o = { ...pp };
  o.chroma = pp.chroma * a; o.glitch = [pp.glitch[0] * a, pp.glitch[1], pp.glitch[2], pp.glitch[3]];
  o.scan = [pp.scan[0] * a, pp.scan[1], pp.scan[2]]; o.flash = [pp.flash[0], pp.flash[1], pp.flash[2], pp.flash[3] * a];
  o.tint = [pp.tint[0], pp.tint[1], pp.tint[2], pp.tint[3] * a];
  o.grade = pp.grade[3] ? [1 + (pp.grade[0] - 1) * a, 1 + (pp.grade[1] - 1) * a, 1 + (pp.grade[2] - 1) * a, pp.grade[3]] : pp.grade;
  o.bloom = [pp.bloom[0] * a, pp.bloom[1], pp.bloom[2]]; o.barrel = pp.barrel * a; o.track = [pp.track[0] * a, pp.track[1], pp.track[2], pp.track[3]];
  o.noise = [pp.noise[0] * a, pp.noise[1]]; o.leak = pp.leak.map((L) => [L[0], L[1], L[2], L[3] * a, L[4], L[5], L[6]]);
  return o;
}
export function scaleParticles(groups, a) {
  if (!groups || a >= 1) return groups;
  return groups.map((g) => { if (!g || !g.fn) return g; const fn = g.fn; return { ...g, fn: (k, rnd, ctx) => { const q = fn(k, rnd, ctx); if (q) return { ...q, opacity: (q.opacity ?? 1) * a }; return q; } }; });
}
